const ICONOS_POR_NOMBRE = new Map(
  ICONOS_PERSONALIZABLES.map((opcion) => [opcion.nombre, opcion.Icono]),
)

/** Alias históricos que pueden venir almacenados en la base de datos. */
const ALIAS: Record<string, string> = {
  AlertTriangle: 'TriangleAlert',
}

export function buscarIcono(nombre: string | null | undefined): LucideIcon | null {
  if (!nombre) return null
  return (
    ICONOS_POR_NOMBRE.get(nombre) ??
    ICONOS_POR_NOMBRE.get(ALIAS[nombre] ?? '') ??
    null
  )
}
