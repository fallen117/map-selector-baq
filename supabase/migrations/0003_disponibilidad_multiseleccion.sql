-- Disponibilidad multiselección para puntos de interés.
-- El catálogo se crea bajo demanda desde el frontend; no se insertan filas semilla.

create table if not exists map_selector.disponibilidad (
  id integer generated by default as identity primary key,
  nombre varchar(60) not null unique,
  icono_nombre varchar(50) not null default '',
  creado_en timestamptz not null default now()
);

create table if not exists map_selector.puntos_interes_disponibilidad (
  punto_id uuid not null
    references map_selector.puntos_interes (id) on delete cascade,
  disponibilidad_id integer not null
    references map_selector.disponibilidad (id) on delete cascade,
  creado_en timestamptz not null default now(),
  primary key (punto_id, disponibilidad_id)
);

-- La descripción se conserva vacía por compatibilidad, pero la UI ya no la usa.
alter table map_selector.puntos_interes
  alter column descripcion set default '';
comment on column map_selector.puntos_interes.descripcion is
  'Campo legado: reemplazado por map_selector.disponibilidad.';

grant usage on sequence map_selector.disponibilidad_id_seq to anon, authenticated;
grant select, insert on map_selector.disponibilidad to anon, authenticated;
grant select, insert, delete on map_selector.puntos_interes_disponibilidad
  to anon, authenticated;

alter table map_selector.disponibilidad enable row level security;
alter table map_selector.puntos_interes_disponibilidad enable row level security;

drop policy if exists "Lectura pública de disponibilidad" on map_selector.disponibilidad;
create policy "Lectura pública de disponibilidad"
  on map_selector.disponibilidad
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Creación pública de disponibilidad" on map_selector.disponibilidad;
create policy "Creación pública de disponibilidad"
  on map_selector.disponibilidad
  for insert
  to anon, authenticated
  with check (nombre in ('Parqueadero', 'Baño', 'Venta de Productos'));

drop policy if exists "Lectura pública de disponibilidad de puntos"
  on map_selector.puntos_interes_disponibilidad;
create policy "Lectura pública de disponibilidad de puntos"
  on map_selector.puntos_interes_disponibilidad
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Asignación pública de disponibilidad"
  on map_selector.puntos_interes_disponibilidad;
create policy "Asignación pública de disponibilidad"
  on map_selector.puntos_interes_disponibilidad
  for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Desasignación pública de disponibilidad"
  on map_selector.puntos_interes_disponibilidad;
create policy "Desasignación pública de disponibilidad"
  on map_selector.puntos_interes_disponibilidad
  for delete
  to anon, authenticated
  using (true);
